// Dish archetypes for the invented corpus: what a 1990s Québécois recipe-card
// box holds, several "matantes" per dish. Each archetype is a template the
// generator varies: title, amounts, which optional lines appear, which written
// form of each ingredient (ingredients.ts) a card uses.
//
// Amount strings: "qty|unit", "qty|unit|note" (can size), "qty|unit|=alt" (the
// other measure for alt), "a-b|unit" a range, "-" no amount, "taste" to_taste.

export interface Line {
  /** Canonical ingredient key from ingredients.ts. */
  i: string;
  /** Amount options, one picked per card. */
  a: string[];
  prep?: string[];
  prepEn?: string[];
  note?: string[];
  noteEn?: string[];
  /** Probability the line is on the card at all (default 1). */
  p?: number;
  /** Probability the line is marked optional. */
  opt?: number;
  /** Alternatives the card names ("beurre ou margarine"), with the probability they appear. */
  or?: string[];
  orP?: number;
  /** A sub-recipe link to a generated pâte (see gen-corpus.ts). */
  recipe?: boolean;
  /** Probability a brand from the ingredient's list goes in `brand:` (default 0.15). */
  brandP?: number;
}

export interface Group {
  g?: string;
  gEn?: string;
  optional?: boolean;
  /** Probability this group appears (default 1). */
  p?: number;
  items: Line[];
}

export interface Dish {
  key: string;
  family: string;
  /** Number of French cards, and of English ones. */
  n: number;
  nEn?: number;
  titles: string[];
  titlesEn?: string[];
  tags: string[];
  season?: string[];
  oven?: string[];
  prep?: string[];
  cook?: string[];
  rest?: string[];
  servings?: number[];
  yields?: string[];
  yieldsEn?: string[];
  difficulty: number[];
  groups: Group[];
  steps: string[];
  stepsEn?: string[];
  notes?: string[];
  notesEn?: string[];
  variantes?: string[];
  variantsEn?: string[];
}

/** Build a line. */
